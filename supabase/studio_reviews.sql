-- Per-academy user reviews. Separate from the community feed.
create table if not exists public.studio_reviews (
  id uuid primary key default gen_random_uuid(),
  studio_id uuid not null references public.studios(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  rating smallint not null check (rating between 1 and 5),
  content text not null check (char_length(btrim(content)) between 5 and 1000),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint studio_reviews_one_per_user unique (studio_id, user_id)
);

create index if not exists studio_reviews_studio_created_idx
  on public.studio_reviews (studio_id, created_at desc);

alter table public.studio_reviews enable row level security;

drop policy if exists "Public can read studio reviews" on public.studio_reviews;
create policy "Public can read studio reviews"
  on public.studio_reviews for select
  to anon, authenticated
  using (true);

-- All signed-in members may review. Attendance verification is a trust badge, not a writing gate.
ALTER TABLE public.studio_reviews
  ADD COLUMN IF NOT EXISTS is_hidden boolean NOT NULL DEFAULT false,
  ADD COLUMN IF NOT EXISTS hidden_reason text;
DROP POLICY IF EXISTS "Users can create own studio reviews" ON public.studio_reviews;
DROP POLICY IF EXISTS "Users can update own studio reviews" ON public.studio_reviews;
DROP POLICY IF EXISTS "Verified students create own studio reviews" ON public.studio_reviews;
DROP POLICY IF EXISTS "Verified students update own studio reviews" ON public.studio_reviews;
CREATE POLICY "Members create own studio reviews"
  ON public.studio_reviews FOR INSERT TO authenticated
  WITH CHECK (user_id=auth.uid());
CREATE POLICY "Members update own studio reviews"
  ON public.studio_reviews FOR UPDATE TO authenticated
  USING (user_id=auth.uid()) WITH CHECK (user_id=auth.uid());
GRANT SELECT ON public.studio_reviews TO anon, authenticated;
GRANT INSERT, UPDATE ON public.studio_reviews TO authenticated;

-- Reports are unique per reporter/review. Three independent reports hide a review
-- pending admin review; reports never delete review history.
CREATE TABLE IF NOT EXISTS public.studio_review_reports (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  review_id uuid NOT NULL REFERENCES public.studio_reviews(id) ON DELETE CASCADE,
  reporter_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  reason text NOT NULL CHECK(reason IN ('광고/홍보','욕설/비방','허위 정보','도배/스팸','개인정보 노출','기타')),
  details text NOT NULL DEFAULT '' CHECK(char_length(details)<=500),
  status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','actioned','dismissed')),
  admin_note text,
  reviewed_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  reviewed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(review_id,reporter_id)
);
ALTER TABLE public.studio_review_reports ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.studio_review_reports FROM PUBLIC,anon,authenticated;
GRANT INSERT,SELECT ON public.studio_review_reports TO authenticated;
DROP POLICY IF EXISTS "Members report studio reviews" ON public.studio_review_reports;
CREATE POLICY "Members report studio reviews"
 ON public.studio_review_reports FOR INSERT TO authenticated
 WITH CHECK(reporter_id=auth.uid() AND EXISTS(
  SELECT 1 FROM public.studio_reviews r WHERE r.id=review_id AND r.user_id<>auth.uid()
 ));
DROP POLICY IF EXISTS "Members read own studio review reports" ON public.studio_review_reports;
CREATE POLICY "Members read own studio review reports"
 ON public.studio_review_reports FOR SELECT TO authenticated USING(reporter_id=auth.uid());

CREATE OR REPLACE FUNCTION public.apply_studio_review_report()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_count integer;
BEGIN
 SELECT count(DISTINCT reporter_id) INTO v_count
 FROM public.studio_review_reports WHERE review_id=NEW.review_id;
 IF v_count>=3 THEN
  UPDATE public.studio_reviews SET is_hidden=true,hidden_reason='신고 3건 이상 · 관리자 검토 대기'
  WHERE id=NEW.review_id;
 END IF;
 RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION public.apply_studio_review_report() FROM PUBLIC,anon,authenticated;
DROP TRIGGER IF EXISTS studio_review_report_auto_hide ON public.studio_review_reports;
CREATE TRIGGER studio_review_report_auto_hide AFTER INSERT ON public.studio_review_reports
FOR EACH ROW EXECUTE FUNCTION public.apply_studio_review_report();

CREATE OR REPLACE FUNCTION public.guard_studio_review_abuse()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_verified_at timestamptz;
BEGIN
 IF auth.uid() IS NULL OR NEW.user_id<>auth.uid() THEN
  RAISE EXCEPTION '본인 계정으로만 리뷰를 작성할 수 있습니다.';
 END IF;
 IF TG_OP='INSERT' THEN
  IF (SELECT count(*) FROM public.studio_reviews
      WHERE user_id=NEW.user_id AND created_at>now()-interval '24 hours')>=3 THEN
   RAISE EXCEPTION '리뷰는 24시간에 최대 3개까지 작성할 수 있습니다.';
  END IF;
  NEW.created_at:=now();
 ELSE
  IF OLD.user_id<>auth.uid() THEN
   IF NOT public.is_balletmate_admin() THEN RAISE EXCEPTION '본인 리뷰만 수정할 수 있습니다.'; END IF;
   -- Admin moderation may change visibility without changing the review author/content.
   NEW.user_id:=OLD.user_id;
   NEW.studio_id:=OLD.studio_id;
   NEW.rating:=OLD.rating;
   NEW.content:=OLD.content;
   NEW.created_at:=OLD.created_at;
  ELSE
   IF OLD.updated_at>now()-interval '10 minutes' THEN
    RAISE EXCEPTION '리뷰 수정은 10분 간격으로 가능합니다.';
   END IF;
   NEW.is_hidden:=OLD.is_hidden;
   NEW.hidden_reason:=OLD.hidden_reason;
  END IF;
 END IF;
 NEW.updated_at:=now();
 SELECT verified_at INTO v_verified_at FROM public.studio_review_verifications
 WHERE studio_id=NEW.studio_id AND user_id=NEW.user_id;
 NEW.verified_at:=v_verified_at;
 NEW.is_hidden:=false;
 NEW.hidden_reason:=NULL;
 RETURN NEW;
END $$;
REVOKE ALL ON FUNCTION public.guard_studio_review_abuse() FROM PUBLIC,anon,authenticated;
DROP TRIGGER IF EXISTS studio_reviews_require_attendance ON public.studio_reviews;
DROP TRIGGER IF EXISTS studio_reviews_guard_abuse ON public.studio_reviews;
CREATE TRIGGER studio_reviews_guard_abuse BEFORE INSERT OR UPDATE ON public.studio_reviews
FOR EACH ROW EXECUTE FUNCTION public.guard_studio_review_abuse();

DROP POLICY IF EXISTS "Public can read studio reviews" ON public.studio_reviews;
CREATE POLICY "Public can read visible studio reviews"
 ON public.studio_reviews FOR SELECT TO anon,authenticated
 USING(is_hidden=false OR user_id=auth.uid() OR public.is_balletmate_admin());

CREATE OR REPLACE FUNCTION public.submit_studio_review_report(
 p_review_id uuid,p_reason text,p_details text DEFAULT ''
)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
 IF auth.uid() IS NULL THEN RAISE EXCEPTION '로그인이 필요합니다.'; END IF;
 INSERT INTO public.studio_review_reports(review_id,reporter_id,reason,details)
 VALUES(p_review_id,auth.uid(),p_reason,left(coalesce(p_details,''),500));
END $$;
REVOKE ALL ON FUNCTION public.submit_studio_review_report(uuid,text,text) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.submit_studio_review_report(uuid,text,text) TO authenticated;

CREATE OR REPLACE FUNCTION public.admin_list_studio_review_reports()
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
BEGIN
 IF NOT public.is_balletmate_admin() THEN RAISE EXCEPTION 'Admin access required'; END IF;
 RETURN coalesce((SELECT jsonb_agg(jsonb_build_object(
  'id',q.id,'review_id',q.review_id,'studio_id',q.studio_id,'studio_name',s.name,
  'reviewer_id',r.user_id,'review_content',r.content,'reason',q.reason,
  'details',q.details,'status',q.status,'created_at',q.created_at
 ) ORDER BY q.created_at DESC)
 FROM (SELECT * FROM public.studio_review_reports ORDER BY created_at DESC LIMIT 100) q
 JOIN public.studio_reviews r ON r.id=q.review_id
 LEFT JOIN public.studios s ON s.id=r.studio_id),'[]'::jsonb);
END $$;
CREATE OR REPLACE FUNCTION public.admin_resolve_studio_review_report(
 p_report_id bigint,p_action text,p_admin_note text DEFAULT NULL
)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=public AS $$
DECLARE v_review_id uuid;
BEGIN
 IF NOT public.is_balletmate_admin() THEN RAISE EXCEPTION 'Admin access required'; END IF;
 IF p_action NOT IN ('hide','restore','dismiss') THEN RAISE EXCEPTION 'Invalid action'; END IF;
 SELECT review_id INTO v_review_id FROM public.studio_review_reports WHERE id=p_report_id;
 IF v_review_id IS NULL THEN RAISE EXCEPTION 'Report not found'; END IF;
 UPDATE public.studio_review_reports SET
  status=CASE WHEN p_action='dismiss' THEN 'dismissed' ELSE 'actioned' END,
  admin_note=nullif(left(coalesce(p_admin_note,''),500),''),
  reviewed_by=auth.uid(),reviewed_at=now()
 WHERE id=p_report_id;
 IF p_action='hide' THEN
  UPDATE public.studio_reviews SET is_hidden=true,hidden_reason='관리자 검토 결과 숨김' WHERE id=v_review_id;
 ELSIF p_action IN ('restore','dismiss') THEN
  UPDATE public.studio_reviews SET is_hidden=false,hidden_reason=NULL WHERE id=v_review_id;
 END IF;
END $$;
REVOKE ALL ON FUNCTION public.admin_list_studio_review_reports() FROM PUBLIC,anon;
REVOKE ALL ON FUNCTION public.admin_resolve_studio_review_report(bigint,text,text) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.admin_list_studio_review_reports() TO authenticated;
GRANT EXECUTE ON FUNCTION public.admin_resolve_studio_review_report(bigint,text,text) TO authenticated;
