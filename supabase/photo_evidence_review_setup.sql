-- Balletmate photo OCR -> evidence review setup.
-- Safe to re-run. Run once in Supabase SQL Editor if these review migrations
-- have not already been applied.

DO $$
BEGIN
  IF to_regclass('public.studio_blog_post_crawl_queue') IS NOT NULL THEN
    ALTER TABLE public.studio_blog_post_crawl_queue
      DROP CONSTRAINT IF EXISTS studio_blog_post_crawl_queue_status_check;
    ALTER TABLE public.studio_blog_post_crawl_queue
      ADD CONSTRAINT studio_blog_post_crawl_queue_status_check
      CHECK (status IN ('pending','processing','completed','failed','rejected'));
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS public.studio_blog_evidence_candidates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  studio_id uuid NOT NULL REFERENCES public.studios(id) ON DELETE CASCADE,
  studio_name text NOT NULL,
  source_id bigint NOT NULL REFERENCES public.studio_blog_sources(id) ON DELETE CASCADE,
  source_title text,
  source_url text NOT NULL,
  candidate_type text NOT NULL CHECK (candidate_type IN ('price','schedule')),
  candidate_value text NOT NULL,
  normalized_value text,
  evidence_text text NOT NULL,
  confidence numeric(3,2) NOT NULL DEFAULT 0.60 CHECK (confidence BETWEEN 0 AND 1),
  review_status text NOT NULL DEFAULT 'pending' CHECK (review_status IN ('pending','verified','rejected')),
  reviewed_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  reviewed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (source_id, candidate_type, candidate_value)
);

ALTER TABLE public.studio_blog_evidence_candidates
  ADD COLUMN IF NOT EXISTS price_period text NOT NULL DEFAULT '기간 미확인',
  ADD COLUMN IF NOT EXISTS price_frequency_per_week integer,
  ADD COLUMN IF NOT EXISTS source_post_date date;

ALTER TABLE public.studio_blog_evidence_candidates
  DROP CONSTRAINT IF EXISTS studio_blog_evidence_candidates_frequency_check;
ALTER TABLE public.studio_blog_evidence_candidates
  ADD CONSTRAINT studio_blog_evidence_candidates_frequency_check
  CHECK (price_frequency_per_week IS NULL OR price_frequency_per_week BETWEEN 1 AND 14);

ALTER TABLE public.studio_image_ocr_results
  ADD COLUMN IF NOT EXISTS source_post_date date;

UPDATE public.studio_blog_evidence_candidates ec
SET source_post_date = s.post_date
FROM public.studio_blog_sources s
WHERE s.id = ec.source_id AND ec.source_post_date IS NULL;

UPDATE public.studio_image_ocr_results o
SET source_post_date = s.post_date
FROM public.studio_blog_sources s
WHERE s.id = o.source_id AND o.source_post_date IS NULL;

CREATE INDEX IF NOT EXISTS studio_blog_evidence_review_idx
  ON public.studio_blog_evidence_candidates(review_status, created_at DESC);
CREATE INDEX IF NOT EXISTS studio_blog_evidence_studio_idx
  ON public.studio_blog_evidence_candidates(studio_id, created_at DESC);
CREATE INDEX IF NOT EXISTS studio_blog_evidence_source_date_idx
  ON public.studio_blog_evidence_candidates(source_post_date);

ALTER TABLE public.studio_blog_evidence_candidates ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.studio_blog_evidence_candidates FROM anon;
GRANT SELECT, INSERT, UPDATE ON public.studio_blog_evidence_candidates TO authenticated;
GRANT ALL ON public.studio_blog_evidence_candidates TO service_role;

DROP POLICY IF EXISTS "admins read evidence candidates" ON public.studio_blog_evidence_candidates;
CREATE POLICY "admins read evidence candidates"
  ON public.studio_blog_evidence_candidates FOR SELECT TO authenticated
  USING (public.is_balletmate_admin());

DROP POLICY IF EXISTS "admins review evidence candidates" ON public.studio_blog_evidence_candidates;
CREATE POLICY "admins review evidence candidates"
  ON public.studio_blog_evidence_candidates FOR UPDATE TO authenticated
  USING (public.is_balletmate_admin())
  WITH CHECK (public.is_balletmate_admin());

DROP POLICY IF EXISTS "admins insert evidence candidates" ON public.studio_blog_evidence_candidates;
CREATE POLICY "admins insert evidence candidates"
  ON public.studio_blog_evidence_candidates FOR INSERT TO authenticated
  WITH CHECK (public.is_balletmate_admin());

COMMENT ON TABLE public.studio_blog_evidence_candidates IS
  'Unverified price/schedule evidence from public posts or administrator-reviewed device OCR. Not published automatically.';
