-- Balletmate push notifications and global announcements.
-- Run once in Supabase SQL Editor. Safe to re-run.
create extension if not exists pg_net with schema extensions;

create table if not exists public.user_push_tokens (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  expo_push_token text not null unique,
  platform text not null default 'unknown' check (platform in ('ios','android','web','unknown')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
alter table public.user_push_tokens drop constraint if exists user_push_tokens_expo_push_token_key;
create unique index if not exists user_push_tokens_user_token_uidx on public.user_push_tokens(user_id,expo_push_token);
create index if not exists user_push_tokens_user_idx on public.user_push_tokens(user_id);
alter table public.user_push_tokens enable row level security;
revoke all on public.user_push_tokens from anon;
grant select,insert,update,delete on public.user_push_tokens to authenticated;
drop policy if exists "users manage own push tokens" on public.user_push_tokens;
create policy "users manage own push tokens" on public.user_push_tokens
for all to authenticated using (user_id=auth.uid()) with check (user_id=auth.uid());

create table if not exists public.user_notification_preferences (
  user_id uuid primary key references auth.users(id) on delete cascade,
  preferences jsonb not null default '{"announcements":true,"messages":true,"replies":false,"recommendations":true,"favoriteNotices":true,"favoritePrices":true,"favoriteSchedules":true}'::jsonb,
  updated_at timestamptz not null default now()
);
alter table public.user_notification_preferences enable row level security;
revoke all on public.user_notification_preferences from anon;
grant select,insert,update,delete on public.user_notification_preferences to authenticated;
drop policy if exists "users manage own notification preferences" on public.user_notification_preferences;
create policy "users manage own notification preferences" on public.user_notification_preferences
for all to authenticated using (user_id=auth.uid()) with check (user_id=auth.uid());

create table if not exists public.app_notices (
  id bigint generated by default as identity primary key,
  title text not null check (length(trim(title)) between 1 and 120),
  body text not null check (length(trim(body)) between 1 and 5000),
  is_active boolean not null default true,
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists app_notices_active_created_idx on public.app_notices(is_active,created_at desc);
alter table public.app_notices enable row level security;
grant select on public.app_notices to anon,authenticated;
grant insert,update,delete on public.app_notices to authenticated;
drop policy if exists "public read active app notices" on public.app_notices;
create policy "public read active app notices" on public.app_notices
for select to anon,authenticated using (is_active=true);
drop policy if exists "admins manage app notices" on public.app_notices;
create policy "admins manage app notices" on public.app_notices
for all to authenticated using (public.is_balletmate_admin()) with check (public.is_balletmate_admin());

-- The Edge Function URL and shared dispatch secret are stored in Vault.
-- Create both secrets after deploying send-push:
-- select vault.create_secret('https://<PROJECT_REF>.supabase.co/functions/v1/send-push','balletmate_push_function_url');
-- select vault.create_secret('<A_LONG_RANDOM_SECRET>','balletmate_push_dispatch_secret');
create or replace function public.dispatch_balletmate_push(p_payload jsonb)
returns void language plpgsql security definer set search_path=''
as $$
declare v_url text; v_secret text;
begin
  select decrypted_secret into v_url from vault.decrypted_secrets where name='balletmate_push_function_url' limit 1;
  select decrypted_secret into v_secret from vault.decrypted_secrets where name='balletmate_push_dispatch_secret' limit 1;
  if coalesce(v_url,'')='' or coalesce(v_secret,'')='' then
    raise warning 'Balletmate push secrets are not configured; notification event was not dispatched.';
    return;
  end if;
  perform net.http_post(
    url:=v_url,
    headers:=jsonb_build_object('Content-Type','application/json','x-push-secret',v_secret),
    body:=p_payload,
    timeout_milliseconds:=5000
  );
end;
$$;
revoke all on function public.dispatch_balletmate_push(jsonb) from public,anon,authenticated;

create or replace function public.notify_favorite_studio_update()
returns trigger language plpgsql security definer set search_path=''
as $$
declare v_studio_id uuid; v_title text; v_body text; v_kind text;
begin
  v_studio_id:=new.studio_id;
  if tg_table_name='studio_owner_notices' then
    v_kind:='favoriteNotices'; v_title:='찜한 학원 공지사항 업데이트';
    v_body:=coalesce(new.title,'새 공지사항이 등록되었습니다.');
  elsif tg_table_name='studio_public_prices' then
    v_kind:='favoritePrices'; v_title:='찜한 학원 가격표 업데이트';
    v_body:='학원 가격 정보가 업데이트되었습니다.';
  else
    v_kind:='favoriteSchedules'; v_title:='찜한 학원 시간표 업데이트';
    v_body:='학원 시간표가 업데이트되었습니다.';
  end if;
  if coalesce(new.is_active,true)=false then return new; end if;
  perform public.dispatch_balletmate_push(jsonb_build_object(
    'scope','favorites','studio_id',v_studio_id,'preference',v_kind,
    'title',v_title,'body',left(v_body,180),'data',jsonb_build_object('studioId',v_studio_id,'kind',v_kind)
  ));
  return new;
end;
$$;
revoke all on function public.notify_favorite_studio_update() from public;

drop trigger if exists push_favorite_studio_notice on public.studio_owner_notices;
create trigger push_favorite_studio_notice after insert or update on public.studio_owner_notices
for each row execute function public.notify_favorite_studio_update();
drop trigger if exists push_favorite_studio_price on public.studio_public_prices;
create trigger push_favorite_studio_price after insert or update on public.studio_public_prices
for each row execute function public.notify_favorite_studio_update();
drop trigger if exists push_favorite_studio_schedule on public.studio_public_schedules;
create trigger push_favorite_studio_schedule after insert or update on public.studio_public_schedules
for each row execute function public.notify_favorite_studio_update();

create or replace function public.notify_global_app_notice()
returns trigger language plpgsql security definer set search_path=''
as $$
begin
  if new.is_active then
    perform public.dispatch_balletmate_push(jsonb_build_object(
      'scope','all','preference','announcements','title',new.title,
      'body',left(new.body,180),'data',jsonb_build_object('noticeId',new.id,'kind','announcement')
    ));
  end if;
  return new;
end;
$$;
revoke all on function public.notify_global_app_notice() from public;
drop trigger if exists push_global_app_notice on public.app_notices;
create trigger push_global_app_notice after insert on public.app_notices
for each row execute function public.notify_global_app_notice();
