-- Free-tier evidence review queue for structured studio data.
-- Safe to run more than once.

do $$
begin
  if exists (
    select 1 from pg_constraint
    where conrelid = 'public.studio_blog_post_crawl_queue'::regclass
      and conname = 'studio_blog_post_crawl_queue_status_check'
  ) then
    alter table public.studio_blog_post_crawl_queue
      drop constraint studio_blog_post_crawl_queue_status_check;
  end if;
  alter table public.studio_blog_post_crawl_queue
    add constraint studio_blog_post_crawl_queue_status_check
    check (status in ('pending','processing','completed','failed','rejected'));
end $$;

create table if not exists public.studio_blog_evidence_candidates (
  id bigint generated by default as identity primary key,
  studio_id uuid not null references public.studios(id) on delete cascade,
  studio_name text not null,
  source_id bigint not null references public.studio_blog_sources(id) on delete cascade,
  source_title text,
  source_url text not null,
  candidate_type text not null check (candidate_type in ('price','schedule')),
  candidate_value text not null,
  normalized_value text,
  evidence_text text not null,
  confidence numeric(3,2) not null default 0.60 check (confidence between 0 and 1),
  review_status text not null default 'pending' check (review_status in ('pending','verified','rejected')),
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  unique (source_id, candidate_type, candidate_value)
);

create index if not exists studio_blog_evidence_review_idx
  on public.studio_blog_evidence_candidates(review_status, created_at desc);
create index if not exists studio_blog_evidence_studio_idx
  on public.studio_blog_evidence_candidates(studio_id, created_at desc);

alter table public.studio_blog_evidence_candidates enable row level security;
revoke all on public.studio_blog_evidence_candidates from anon;
grant select, update on public.studio_blog_evidence_candidates to authenticated;
grant all on public.studio_blog_evidence_candidates to service_role;

drop policy if exists "admins read evidence candidates" on public.studio_blog_evidence_candidates;
create policy "admins read evidence candidates"
  on public.studio_blog_evidence_candidates
  for select to authenticated
  using (public.is_balletmate_admin());

drop policy if exists "admins review evidence candidates" on public.studio_blog_evidence_candidates;
create policy "admins review evidence candidates"
  on public.studio_blog_evidence_candidates
  for update to authenticated
  using (public.is_balletmate_admin())
  with check (public.is_balletmate_admin());

comment on table public.studio_blog_evidence_candidates is
  'Unverified public-source price/schedule evidence. Review status never publishes structured class data automatically.';
