-- Verified official Naver blog accounts for Balletmate studio discovery.
-- This is account-level verification only; extracted prices/schedules still require admin review.

CREATE TABLE IF NOT EXISTS public.studio_blog_official_accounts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  studio_name text NOT NULL,
  blogger_url text NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  verified_at timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT studio_blog_official_accounts_studio_account_key UNIQUE (studio_name, blogger_url)
);

ALTER TABLE public.studio_blog_official_accounts ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.studio_blog_official_accounts FROM anon, authenticated;
GRANT ALL ON public.studio_blog_official_accounts TO service_role;

-- W Ballet: confirmed by the supplied Naver search records (blogger name: 더블유발레).
INSERT INTO public.studio_blog_official_accounts (studio_name, blogger_url, is_active, verified_at)
SELECT s.name, 'https://blog.naver.com/wballet', true, now()
FROM public.studios s
WHERE s.name = 'W발레스튜디오'
ON CONFLICT (studio_name, blogger_url)
DO UPDATE SET is_active = true, verified_at = now();

-- Keep rejected sources from appearing as successfully crawled content.
UPDATE public.studio_blog_post_contents c
SET crawl_status = 'rejected',
    checked_at = now()
FROM public.studio_blog_post_crawl_queue q
WHERE q.source_id = c.source_id
  AND q.status = 'rejected'
  AND c.crawl_status IN ('success', 'partial');

-- Remove review candidates extracted from sources that have since been rejected.
DELETE FROM public.studio_blog_evidence_candidates e
USING public.studio_blog_post_crawl_queue q
WHERE q.source_id = e.source_id
  AND q.status = 'rejected';
