-- Schedule evidence to structured class candidates. Admin-reviewed only; repeat-safe.
CREATE TABLE IF NOT EXISTS public.studio_schedule_class_candidates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  evidence_candidate_id bigint NOT NULL REFERENCES public.studio_blog_evidence_candidates(id) ON DELETE CASCADE,
  studio_id uuid NOT NULL REFERENCES public.studios(id) ON DELETE CASCADE,
  studio_name text NOT NULL,
  source_title text,
  source_url text NOT NULL,
  source_post_date date,
  source_text text NOT NULL,
  proposed_title text NOT NULL,
  audience text NOT NULL DEFAULT 'all' CHECK (audience IN ('adult','kids','all')),
  proposed_level text,
  proposed_class_type text,
  sessions jsonb NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(sessions)='array'),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','creating','created','rejected')),
  created_class_id uuid REFERENCES public.classes(id) ON DELETE SET NULL,
  reviewed_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  reviewed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE(evidence_candidate_id)
);
CREATE INDEX IF NOT EXISTS studio_schedule_class_candidates_review_idx
  ON public.studio_schedule_class_candidates(status,created_at DESC);
ALTER TABLE public.studio_schedule_class_candidates ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.studio_schedule_class_candidates FROM anon, authenticated;
GRANT SELECT, INSERT, UPDATE, DELETE ON public.studio_schedule_class_candidates TO authenticated;
GRANT ALL ON public.studio_schedule_class_candidates TO service_role;
DROP POLICY IF EXISTS "admins manage schedule class candidates" ON public.studio_schedule_class_candidates;
CREATE POLICY "admins manage schedule class candidates"
  ON public.studio_schedule_class_candidates FOR ALL TO authenticated
  USING (public.is_balletmate_admin()) WITH CHECK (public.is_balletmate_admin());
GRANT USAGE, SELECT ON SEQUENCE public.studio_schedule_class_candidates_id_seq TO authenticated, service_role;
