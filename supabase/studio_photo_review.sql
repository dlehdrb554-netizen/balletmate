-- Official-site photo candidates are reviewed by an administrator before being
-- added to studios.image_urls. This workflow does not use OCR.
-- Safe to run repeatedly.

CREATE TABLE IF NOT EXISTS public.studio_photo_candidates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  studio_id uuid NOT NULL REFERENCES public.studios(id) ON DELETE CASCADE,
  studio_name text NOT NULL,
  image_url text NOT NULL,
  source_page_url text NOT NULL,
  source_host text,
  review_status text NOT NULL DEFAULT 'pending'
    CHECK (review_status IN ('pending','approved','rejected')),
  created_at timestamptz NOT NULL DEFAULT now(),
  reviewed_at timestamptz,
  reviewed_by uuid REFERENCES auth.users(id) ON DELETE SET NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS studio_photo_candidates_unique_image
  ON public.studio_photo_candidates(studio_id,image_url);
CREATE INDEX IF NOT EXISTS studio_photo_candidates_review_idx
  ON public.studio_photo_candidates(review_status,created_at DESC);

ALTER TABLE public.studio_photo_candidates ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.studio_photo_candidates FROM anon;
GRANT SELECT, UPDATE ON public.studio_photo_candidates TO authenticated;
GRANT ALL ON public.studio_photo_candidates TO service_role;

DROP POLICY IF EXISTS "admins view studio photo candidates" ON public.studio_photo_candidates;
CREATE POLICY "admins view studio photo candidates"
  ON public.studio_photo_candidates FOR SELECT TO authenticated
  USING (public.is_balletmate_admin());

DROP POLICY IF EXISTS "admins review studio photo candidates" ON public.studio_photo_candidates;
CREATE POLICY "admins review studio photo candidates"
  ON public.studio_photo_candidates FOR UPDATE TO authenticated
  USING (public.is_balletmate_admin())
  WITH CHECK (public.is_balletmate_admin());
