-- Report resolution workflow and audit trail for administrator edits to studio records.
-- Apply after studio_user_reports.sql.

CREATE TABLE IF NOT EXISTS public.studio_information_change_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  studio_id uuid NOT NULL REFERENCES public.studios(id) ON DELETE CASCADE,
  actor_id uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  changed_fields jsonb NOT NULL DEFAULT '{}'::jsonb,
  changed_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS studio_information_change_logs_studio_time_idx
  ON public.studio_information_change_logs(studio_id, changed_at DESC);

ALTER TABLE public.studio_information_change_logs ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.studio_information_change_logs FROM anon, authenticated;
GRANT SELECT ON public.studio_information_change_logs TO authenticated;
GRANT ALL ON public.studio_information_change_logs TO service_role;

DROP POLICY IF EXISTS "admins read studio information change logs" ON public.studio_information_change_logs;
CREATE POLICY "admins read studio information change logs"
  ON public.studio_information_change_logs
  FOR SELECT TO authenticated
  USING (public.is_balletmate_admin());

CREATE OR REPLACE FUNCTION public.log_studio_information_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $studio_change_log$
DECLARE
  before_values jsonb;
  after_values jsonb;
  differences jsonb;
BEGIN
  before_values := jsonb_build_object(
    'name', OLD.name,
    'latitude', OLD.latitude,
    'longitude', OLD.longitude,
    'district', OLD.district,
    'address', OLD.address,
    'phone', OLD.phone,
    'website_url', OLD.website_url,
    'source_url', OLD.source_url,
    'source_name', OLD.source_name,
    'verified_at', OLD.verified_at,
    'image_urls', OLD.image_urls,
    'image_source_name', OLD.image_source_name,
    'image_usage_note', OLD.image_usage_note,
    'price_per_class', OLD.price_per_class,
    'adult_classes', OLD.adult_classes,
    'kids_classes', OLD.kids_classes,
    'is_active', OLD.is_active
  );
  after_values := jsonb_build_object(
    'name', NEW.name,
    'latitude', NEW.latitude,
    'longitude', NEW.longitude,
    'district', NEW.district,
    'address', NEW.address,
    'phone', NEW.phone,
    'website_url', NEW.website_url,
    'source_url', NEW.source_url,
    'source_name', NEW.source_name,
    'verified_at', NEW.verified_at,
    'image_urls', NEW.image_urls,
    'image_source_name', NEW.image_source_name,
    'image_usage_note', NEW.image_usage_note,
    'price_per_class', NEW.price_per_class,
    'adult_classes', NEW.adult_classes,
    'kids_classes', NEW.kids_classes,
    'is_active', NEW.is_active
  );

  SELECT jsonb_object_agg(
    old_entry.key,
    jsonb_build_object('before', old_entry.value, 'after', new_entry.value)
  )
  INTO differences
  FROM jsonb_each(before_values) AS old_entry
  JOIN jsonb_each(after_values) AS new_entry USING (key)
  WHERE old_entry.value IS DISTINCT FROM new_entry.value;

  IF differences IS NOT NULL THEN
    INSERT INTO public.studio_information_change_logs(studio_id, actor_id, changed_fields)
    VALUES (NEW.id, auth.uid(), differences);
  END IF;
  RETURN NEW;
END;
$studio_change_log$;

DROP TRIGGER IF EXISTS studios_information_change_log ON public.studios;
CREATE TRIGGER studios_information_change_log
AFTER UPDATE ON public.studios
FOR EACH ROW
EXECUTE FUNCTION public.log_studio_information_change();

CREATE OR REPLACE FUNCTION public.admin_list_studio_information_change_logs(
  p_studio_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $studio_change_history$
BEGIN
  IF NOT public.is_balletmate_admin() THEN
    RAISE EXCEPTION 'Admin access required';
  END IF;

  RETURN COALESCE((
    SELECT jsonb_agg(row_data ORDER BY changed_at DESC)
    FROM (
      SELECT jsonb_build_object(
        'id', l.id,
        'actor_id', l.actor_id,
        'changed_fields', l.changed_fields,
        'changed_at', l.changed_at
      ) AS row_data, l.changed_at
      FROM public.studio_information_change_logs l
      WHERE l.studio_id = p_studio_id
      ORDER BY l.changed_at DESC
      LIMIT 30
    ) history
  ), '[]'::jsonb);
END;
$studio_change_history$;

REVOKE ALL ON FUNCTION public.admin_list_studio_information_change_logs(uuid) FROM public, anon;
GRANT EXECUTE ON FUNCTION public.admin_list_studio_information_change_logs(uuid) TO authenticated;

