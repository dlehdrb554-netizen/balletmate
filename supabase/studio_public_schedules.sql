-- Publish only administrator-reviewed schedule evidence from public sources.
-- Schedule text remains source-faithful; it is not converted into invented class names.
-- Safe to run more than once.

CREATE TABLE IF NOT EXISTS public.studio_public_schedules (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  candidate_id bigint NOT NULL UNIQUE REFERENCES public.studio_blog_evidence_candidates(id) ON DELETE CASCADE,
  studio_id uuid NOT NULL REFERENCES public.studios(id) ON DELETE CASCADE,
  schedule_text text NOT NULL CHECK (length(trim(schedule_text)) > 0),
  evidence_text text NOT NULL,
  source_title text,
  source_url text NOT NULL,
  source_post_date date,
  published_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  published_at timestamptz NOT NULL DEFAULT now(),
  expires_at date NOT NULL DEFAULT (CURRENT_DATE + 180),
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS studio_public_schedules_studio_active_idx
  ON public.studio_public_schedules(studio_id, is_active, published_at DESC);
CREATE INDEX IF NOT EXISTS studio_public_schedules_expiry_idx
  ON public.studio_public_schedules(is_active, expires_at);

ALTER TABLE public.studio_public_schedules ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.studio_public_schedules FROM anon, authenticated;
GRANT SELECT ON public.studio_public_schedules TO anon, authenticated;
GRANT INSERT, UPDATE, SELECT ON public.studio_public_schedules TO authenticated;
GRANT ALL ON public.studio_public_schedules TO service_role;

DROP POLICY IF EXISTS "public read active studio schedules" ON public.studio_public_schedules;
CREATE POLICY "public read active studio schedules"
  ON public.studio_public_schedules FOR SELECT
  TO anon, authenticated
  USING (is_active = true AND expires_at >= CURRENT_DATE);

DROP POLICY IF EXISTS "admins manage studio public schedules" ON public.studio_public_schedules;
CREATE POLICY "admins manage studio public schedules"
  ON public.studio_public_schedules FOR ALL
  TO authenticated
  USING (public.is_balletmate_admin())
  WITH CHECK (public.is_balletmate_admin());

CREATE OR REPLACE VIEW public.studio_public_schedules_app
WITH (security_invoker = true) AS
SELECT
  s.id, s.studio_id, s.schedule_text, s.evidence_text, s.source_title,
  s.source_url, s.source_post_date, s.published_at, s.expires_at
FROM public.studio_public_schedules s
WHERE s.is_active = true
  AND s.expires_at >= CURRENT_DATE;

GRANT SELECT ON public.studio_public_schedules_app TO anon, authenticated;

COMMENT ON TABLE public.studio_public_schedules IS
  'Administrator-published schedule evidence. Text is preserved from public-source evidence and expires after 180 days.';
