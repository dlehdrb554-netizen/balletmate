-- Owner-entered public timetable text. No crawler/evidence/photo dependency.
-- Safe to re-run.
CREATE TABLE IF NOT EXISTS public.studio_public_schedules (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 studio_id uuid NOT NULL REFERENCES public.studios(id) ON DELETE CASCADE,
 schedule_text text NOT NULL CHECK(length(trim(schedule_text))>0),
 published_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
 published_at timestamptz NOT NULL DEFAULT now(),
 expires_at date NOT NULL DEFAULT (CURRENT_DATE+180),
 is_active boolean NOT NULL DEFAULT true,
 created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.studio_public_schedules ADD COLUMN IF NOT EXISTS expires_at date NOT NULL DEFAULT (CURRENT_DATE+180);
CREATE INDEX IF NOT EXISTS studio_public_schedules_studio_active_idx ON public.studio_public_schedules(studio_id,is_active,published_at DESC);
CREATE INDEX IF NOT EXISTS studio_public_schedules_expiry_idx ON public.studio_public_schedules(is_active,expires_at);
ALTER TABLE public.studio_public_schedules ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.studio_public_schedules TO anon,authenticated;
GRANT INSERT,UPDATE,SELECT ON public.studio_public_schedules TO authenticated;
GRANT ALL ON public.studio_public_schedules TO service_role;
DROP POLICY IF EXISTS "public read active studio schedules" ON public.studio_public_schedules;
CREATE POLICY "public read active studio schedules" ON public.studio_public_schedules FOR SELECT TO anon,authenticated USING(is_active=true AND expires_at>=CURRENT_DATE);
DROP POLICY IF EXISTS "admins manage studio public schedules" ON public.studio_public_schedules;
CREATE POLICY "admins manage studio public schedules" ON public.studio_public_schedules FOR ALL TO authenticated USING(public.is_balletmate_admin()) WITH CHECK(public.is_balletmate_admin());
DROP VIEW IF EXISTS public.studio_public_schedules_app CASCADE;
CREATE VIEW public.studio_public_schedules_app WITH (security_invoker=true) AS
 SELECT id,studio_id,schedule_text,published_at,expires_at
 FROM public.studio_public_schedules WHERE is_active=true AND expires_at>=CURRENT_DATE;
GRANT SELECT ON public.studio_public_schedules_app TO anon,authenticated;
