-- Admin-only management for verified official Naver blog accounts.
-- Run once in Supabase SQL Editor. Public users cannot read or modify this table.

ALTER TABLE public.studio_blog_official_accounts
  ADD COLUMN IF NOT EXISTS studio_id uuid REFERENCES public.studios(id) ON DELETE CASCADE;

-- Backfill only names that identify exactly one academy. Duplicate academy names
-- must be assigned explicitly through the admin screen to avoid cross-linking.
UPDATE public.studio_blog_official_accounts a
SET studio_id = matched.id
FROM (
  SELECT name, min(id::text)::uuid AS id
  FROM public.studios
  GROUP BY name
  HAVING count(*) = 1
) matched
WHERE a.studio_name = matched.name
  AND a.studio_id IS NULL;

ALTER TABLE public.studio_blog_official_accounts
  DROP CONSTRAINT IF EXISTS studio_blog_official_accounts_studio_account_key;
DROP INDEX IF EXISTS public.studio_blog_official_accounts_studio_id_url_key;
CREATE UNIQUE INDEX studio_blog_official_accounts_studio_id_url_key
  ON public.studio_blog_official_accounts(studio_id, blogger_url);

CREATE OR REPLACE FUNCTION public.admin_get_studio_official_blog_accounts(p_studio_id uuid)
RETURNS TABLE(blogger_url text, verified_at timestamptz)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE studio_name_value text;
BEGIN
  IF NOT public.is_balletmate_admin() THEN
    RAISE EXCEPTION 'administrator required' USING ERRCODE = '42501';
  END IF;

  SELECT s.name INTO studio_name_value
  FROM public.studios s
  WHERE s.id = p_studio_id;

  IF studio_name_value IS NULL THEN
    RAISE EXCEPTION 'studio not found';
  END IF;

  RETURN QUERY
  SELECT a.blogger_url, a.verified_at
  FROM public.studio_blog_official_accounts a
  WHERE a.studio_id = p_studio_id
    AND a.is_active = true
  ORDER BY a.verified_at DESC, a.id DESC;
END;
$function$;

CREATE OR REPLACE FUNCTION public.admin_set_studio_official_blog_accounts(
  p_studio_id uuid,
  p_blogger_urls text[]
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE
  studio_name_value text;
  clean_urls text[];
  inserted_count integer := 0;
BEGIN
  IF NOT public.is_balletmate_admin() THEN
    RAISE EXCEPTION 'administrator required' USING ERRCODE = '42501';
  END IF;

  SELECT s.name INTO studio_name_value
  FROM public.studios s
  WHERE s.id = p_studio_id;

  IF studio_name_value IS NULL THEN
    RAISE EXCEPTION 'studio not found';
  END IF;

  SELECT COALESCE(array_agg(url ORDER BY url), ARRAY[]::text[])
  INTO clean_urls
  FROM (
    SELECT DISTINCT trim(value) AS url
    FROM unnest(COALESCE(p_blogger_urls, ARRAY[]::text[])) AS value
    WHERE trim(value) <> ''
  ) normalized;

  IF cardinality(clean_urls) > 5 THEN
    RAISE EXCEPTION '학원별 공식 블로그는 최대 5개까지 등록할 수 있습니다.';
  END IF;

  IF EXISTS (
    SELECT 1 FROM unnest(clean_urls) AS value
    WHERE value !~* '^https://(m[.])?blog[.]naver[.]com/[A-Za-z0-9._-]+/?$'
  ) THEN
    RAISE EXCEPTION '네이버 블로그 프로필 주소만 등록할 수 있습니다. 예: https://blog.naver.com/blogid';
  END IF;

  UPDATE public.studio_blog_official_accounts
  SET is_active = false
  WHERE is_active = true
    AND (studio_id = p_studio_id OR (studio_id IS NULL AND studio_name = studio_name_value));

  INSERT INTO public.studio_blog_official_accounts(studio_id, studio_name, blogger_url, is_active, verified_at)
  SELECT p_studio_id, studio_name_value, value, true, now()
  FROM unnest(clean_urls) AS value
  ON CONFLICT (studio_id, blogger_url)
  DO UPDATE SET is_active = true, verified_at = now();

  GET DIAGNOSTICS inserted_count = ROW_COUNT;
  RETURN inserted_count;
END;
$function$;

REVOKE ALL ON FUNCTION public.admin_get_studio_official_blog_accounts(uuid) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.admin_set_studio_official_blog_accounts(uuid, text[]) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.admin_get_studio_official_blog_accounts(uuid) TO authenticated;
GRANT EXECUTE ON FUNCTION public.admin_set_studio_official_blog_accounts(uuid, text[]) TO authenticated;


-- Discover likely official Naver blog accounts without auto-publishing them.
-- Run once in Supabase SQL Editor after studio_official_blog_admin.sql.

CREATE TABLE IF NOT EXISTS public.studio_blog_account_candidates (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  studio_id uuid NOT NULL REFERENCES public.studios(id) ON DELETE CASCADE,
  studio_name text NOT NULL,
  blogger_url text NOT NULL,
  blogger_name text,
  matched_post_count integer NOT NULL DEFAULT 1,
  sample_posts jsonb NOT NULL DEFAULT '[]'::jsonb,
  match_score integer NOT NULL DEFAULT 0,
  review_status text NOT NULL DEFAULT 'pending'
    CHECK (review_status IN ('pending','approved','rejected')),
  first_seen_at timestamptz NOT NULL DEFAULT now(),
  last_seen_at timestamptz NOT NULL DEFAULT now(),
  reviewed_at timestamptz,
  UNIQUE (studio_id, blogger_url)
);

CREATE INDEX IF NOT EXISTS studio_blog_account_candidates_review_idx
  ON public.studio_blog_account_candidates(studio_id, review_status, match_score DESC, last_seen_at DESC);

ALTER TABLE public.studio_blog_account_candidates ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.studio_blog_account_candidates FROM anon, authenticated;
GRANT ALL ON public.studio_blog_account_candidates TO service_role;

CREATE OR REPLACE FUNCTION public.admin_list_studio_blog_account_candidates(p_studio_id uuid)
RETURNS TABLE(
  id bigint,
  blogger_url text,
  blogger_name text,
  matched_post_count integer,
  sample_posts jsonb,
  match_score integer,
  review_status text,
  last_seen_at timestamptz
)
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $function$
BEGIN
  IF NOT public.is_balletmate_admin() THEN
    RAISE EXCEPTION 'administrator required' USING ERRCODE = '42501';
  END IF;

  RETURN QUERY
  SELECT c.id, c.blogger_url, c.blogger_name, c.matched_post_count,
         c.sample_posts, c.match_score, c.review_status, c.last_seen_at
  FROM public.studio_blog_account_candidates c
  WHERE c.studio_id = p_studio_id
  ORDER BY CASE c.review_status WHEN 'pending' THEN 0 WHEN 'approved' THEN 1 ELSE 2 END,
           c.match_score DESC, c.matched_post_count DESC, c.last_seen_at DESC
  LIMIT 30;
END;
$function$;

CREATE OR REPLACE FUNCTION public.admin_review_studio_blog_account_candidate(
  p_candidate_id bigint,
  p_status text
)
RETURNS boolean
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $function$
DECLARE candidate_row public.studio_blog_account_candidates%ROWTYPE;
BEGIN
  IF NOT public.is_balletmate_admin() THEN
    RAISE EXCEPTION 'administrator required' USING ERRCODE = '42501';
  END IF;
  IF p_status NOT IN ('approved','rejected') THEN
    RAISE EXCEPTION 'invalid review status';
  END IF;

  SELECT * INTO candidate_row
  FROM public.studio_blog_account_candidates
  WHERE id = p_candidate_id
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'candidate not found';
  END IF;

  UPDATE public.studio_blog_account_candidates
  SET review_status = p_status, reviewed_at = now()
  WHERE id = p_candidate_id;

  IF p_status = 'approved' THEN
    INSERT INTO public.studio_blog_official_accounts
      (studio_id, studio_name, blogger_url, is_active, verified_at)
    VALUES
      (candidate_row.studio_id, candidate_row.studio_name,
       candidate_row.blogger_url, true, now())
    ON CONFLICT (studio_id, blogger_url)
    DO UPDATE SET is_active = true, verified_at = now(),
                  studio_name = EXCLUDED.studio_name;
  END IF;

  RETURN true;
END;
$function$;

REVOKE ALL ON FUNCTION public.admin_list_studio_blog_account_candidates(uuid) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.admin_review_studio_blog_account_candidate(bigint, text) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.admin_list_studio_blog_account_candidates(uuid) TO authenticated;
GRANT EXECUTE ON FUNCTION public.admin_review_studio_blog_account_candidate(bigint, text) TO authenticated;


-- Re-run discovery for active academies that do not yet have a verified official account.
-- The existing 5-minute worker processes this queue gradually using the configured Naver API.
UPDATE public.studio_blog_search_queue q
SET status = 'pending',
    attempts = 0,
    last_error = NULL,
    updated_at = now()
FROM public.studios s
WHERE q.studio_id = s.id
  AND coalesce(s.is_active, true)
  AND NOT EXISTS (
    SELECT 1
    FROM public.studio_blog_official_accounts a
    WHERE a.is_active = true
      AND (a.studio_id = s.id OR (a.studio_id IS NULL AND a.studio_name = s.name))
  );
