-- Local on-device OCR results for academy price/schedule images.
-- Images are processed on the administrator's device and are NOT uploaded.
create table if not exists public.studio_image_ocr_results (
  id bigint generated by default as identity primary key,
  studio_id uuid not null references public.studios(id) on delete cascade,
  studio_name text not null,
  image_label text not null,
  extracted_text text not null,
  detected_kind text not null default 'unknown'
    check (detected_kind in ('price','schedule','unknown')),
  review_status text not null default 'pending'
    check (review_status in ('pending','verified','rejected')),
  created_by uuid references auth.users(id) on delete set null,
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);

create index if not exists studio_image_ocr_review_idx
  on public.studio_image_ocr_results(review_status, created_at desc);
create index if not exists studio_image_ocr_studio_idx
  on public.studio_image_ocr_results(studio_id, created_at desc);

alter table public.studio_image_ocr_results enable row level security;
revoke all on public.studio_image_ocr_results from anon, authenticated;
grant select, insert, update on public.studio_image_ocr_results to authenticated;
grant all on public.studio_image_ocr_results to service_role;

drop policy if exists "admins manage local OCR results" on public.studio_image_ocr_results;
create policy "admins manage local OCR results"
  on public.studio_image_ocr_results
  for all to authenticated
  using (public.is_balletmate_admin())
  with check (public.is_balletmate_admin());

comment on table public.studio_image_ocr_results is
  'OCR text extracted locally on an admin device from academy images. Text remains unverified and is never published automatically.';
