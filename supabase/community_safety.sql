-- Community safety controls: member reports and user blocking.
-- Run after community.sql and admin_security.sql. Safe to re-run.

create table if not exists public.community_user_blocks (
  blocker_id uuid not null references auth.users(id) on delete cascade,
  blocked_user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (blocker_id, blocked_user_id),
  constraint community_user_blocks_no_self check (blocker_id <> blocked_user_id)
);
create index if not exists community_user_blocks_blocked_idx
  on public.community_user_blocks(blocked_user_id);

create table if not exists public.community_reports (
  id bigint generated by default as identity primary key,
  reporter_id uuid not null references auth.users(id) on delete cascade,
  target_user_id uuid references auth.users(id) on delete set null,
  content_type text not null check (content_type in ('post','comment')),
  content_id uuid not null,
  reason text not null check (reason in ('스팸/광고','욕설/괴롭힘','부적절한 콘텐츠','개인정보 노출','허위 정보','기타')),
  details text not null default '' check (char_length(details) <= 1000),
  status text not null default 'pending' check (status in ('pending','in_review','actioned','dismissed')),
  admin_note text,
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  unique (reporter_id, content_type, content_id)
);
create index if not exists community_reports_status_created_idx
  on public.community_reports(status, created_at desc);

alter table public.community_user_blocks enable row level security;
alter table public.community_reports enable row level security;
revoke all on public.community_user_blocks from anon, authenticated;
revoke all on public.community_reports from anon, authenticated;
grant select, insert, delete on public.community_user_blocks to authenticated;
grant insert, select on public.community_reports to authenticated;
grant all on public.community_reports to service_role;

drop policy if exists "members manage their own blocks" on public.community_user_blocks;
create policy "members manage their own blocks" on public.community_user_blocks
  for all to authenticated
  using (blocker_id = auth.uid())
  with check (blocker_id = auth.uid() and blocker_id <> blocked_user_id);

drop policy if exists "members submit community reports" on public.community_reports;
create policy "members submit community reports" on public.community_reports
  for insert to authenticated
  with check (reporter_id = auth.uid() and (target_user_id is null or reporter_id <> target_user_id));

drop policy if exists "members read own community reports" on public.community_reports;
create policy "members read own community reports" on public.community_reports
  for select to authenticated using (reporter_id = auth.uid());

drop policy if exists "admins read community reports" on public.community_reports;
create policy "admins read community reports" on public.community_reports
  for select to authenticated using (public.is_balletmate_admin());

create or replace function public.admin_list_community_reports()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_balletmate_admin() then raise exception 'Admin access required'; end if;
  return coalesce((
    select jsonb_agg(to_jsonb(r) order by r.created_at desc)
    from (select * from public.community_reports order by created_at desc limit 100) r
  ), '[]'::jsonb);
end;
$$;

create or replace function public.admin_update_community_report(
  p_report_id bigint,
  p_status text,
  p_admin_note text default null
)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_balletmate_admin() then raise exception 'Admin access required'; end if;
  if p_status not in ('in_review','actioned','dismissed') then raise exception 'Invalid report status'; end if;
  update public.community_reports
  set status = p_status,
      admin_note = nullif(left(coalesce(p_admin_note,''),1000),''),
      reviewed_by = auth.uid(),
      reviewed_at = now()
  where id = p_report_id;
  return found;
end;
$$;
revoke all on function public.admin_list_community_reports() from public, anon;
revoke all on function public.admin_update_community_report(bigint,text,text) from public, anon;
grant execute on function public.admin_list_community_reports() to authenticated;
grant execute on function public.admin_update_community_report(bigint,text,text) to authenticated;
