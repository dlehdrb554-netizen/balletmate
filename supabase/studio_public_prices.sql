-- Owner-entered public price information. No crawler/evidence/photo dependency.
-- Safe to re-run.
CREATE TABLE IF NOT EXISTS public.studio_public_prices (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 studio_id uuid NOT NULL REFERENCES public.studios(id) ON DELETE CASCADE,
 amount_krw integer NOT NULL CHECK(amount_krw>0),
 price_period text NOT NULL CHECK(length(trim(price_period))>0),
 frequency_per_week integer CHECK(frequency_per_week IS NULL OR frequency_per_week BETWEEN 1 AND 14),
 published_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
 published_at timestamptz NOT NULL DEFAULT now(),
 expires_at date NOT NULL DEFAULT (CURRENT_DATE+180),
 is_active boolean NOT NULL DEFAULT true,
 created_at timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE public.studio_public_prices ADD COLUMN IF NOT EXISTS expires_at date NOT NULL DEFAULT (CURRENT_DATE+180);
CREATE INDEX IF NOT EXISTS studio_public_prices_studio_active_idx ON public.studio_public_prices(studio_id,is_active,published_at DESC);
ALTER TABLE public.studio_public_prices ENABLE ROW LEVEL SECURITY;
GRANT SELECT ON public.studio_public_prices TO anon,authenticated;
GRANT INSERT,UPDATE,SELECT ON public.studio_public_prices TO authenticated;
GRANT ALL ON public.studio_public_prices TO service_role;
DROP POLICY IF EXISTS "public read active studio prices" ON public.studio_public_prices;
CREATE POLICY "public read active studio prices" ON public.studio_public_prices FOR SELECT TO anon,authenticated USING(is_active=true AND expires_at>=CURRENT_DATE);
DROP POLICY IF EXISTS "admins manage studio public prices" ON public.studio_public_prices;
CREATE POLICY "admins manage studio public prices" ON public.studio_public_prices FOR ALL TO authenticated USING(public.is_balletmate_admin()) WITH CHECK(public.is_balletmate_admin());
DROP VIEW IF EXISTS public.studio_public_prices_app CASCADE;
CREATE VIEW public.studio_public_prices_app WITH (security_invoker=true) AS
 SELECT id,studio_id,amount_krw,price_period,frequency_per_week,published_at,expires_at
 FROM public.studio_public_prices WHERE is_active=true AND expires_at>=CURRENT_DATE;
GRANT SELECT ON public.studio_public_prices_app TO anon,authenticated;
