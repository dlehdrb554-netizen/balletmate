-- Publish only explicitly reviewed price evidence to the public app.
-- Safe to run more than once.
create table if not exists public.studio_public_prices (
  id bigint generated by default as identity primary key,
  candidate_id bigint not null unique references public.studio_blog_evidence_candidates(id) on delete cascade,
  studio_id uuid not null references public.studios(id) on delete cascade,
  amount_krw integer not null check (amount_krw > 0),
  price_period text not null check (price_period <> '기간 미확인' and length(trim(price_period)) > 0),
  frequency_per_week integer check (frequency_per_week is null or frequency_per_week between 1 and 14),
  evidence_text text not null,
  source_title text,
  source_url text not null,
  source_post_date date,
  published_by uuid references auth.users(id) on delete set null,
  published_at timestamptz not null default now(),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create index if not exists studio_public_prices_studio_active_idx
  on public.studio_public_prices(studio_id, is_active, published_at desc);

alter table public.studio_public_prices enable row level security;
revoke all on public.studio_public_prices from anon, authenticated;
grant select on public.studio_public_prices to anon, authenticated;
grant insert, update, select on public.studio_public_prices to authenticated;
grant all on public.studio_public_prices to service_role;

drop policy if exists "public read active studio prices" on public.studio_public_prices;
create policy "public read active studio prices"
  on public.studio_public_prices for select
  to anon, authenticated
  using (is_active = true);

drop policy if exists "admins manage studio public prices" on public.studio_public_prices;
create policy "admins manage studio public prices"
  on public.studio_public_prices for all
  to authenticated
  using (public.is_balletmate_admin())
  with check (public.is_balletmate_admin());

-- Expose source post date to the publication workflow without trusting client input.
create or replace view public.studio_public_prices_app
with (security_invoker = true) as
select
  p.id, p.studio_id, p.amount_krw, p.price_period,
  p.frequency_per_week, p.evidence_text, p.source_title,
  p.source_url, p.source_post_date, p.published_at
from public.studio_public_prices p
where p.is_active = true;

grant select on public.studio_public_prices_app to anon, authenticated;

comment on table public.studio_public_prices is
  'Prices explicitly published by an administrator from reviewed public-source evidence. Not crawler guesses.';
