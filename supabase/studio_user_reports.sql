-- User reports about academy information. Admin-only review.
create table if not exists public.studio_user_reports (
  id bigint generated by default as identity primary key,
  studio_id uuid not null references public.studios(id) on delete cascade,
  reporter_id uuid not null references auth.users(id) on delete cascade,
  category text not null check (category in ('폐업/이전','주소 오류','전화/홈페이지 오류','가격/시간표 오류','사진 오류','기타')),
  description text not null check (length(trim(description)) between 5 and 1000),
  status text not null default 'pending' check (status in ('pending','in_review','resolved','rejected')),
  admin_note text,
  reviewed_by uuid references auth.users(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists studio_user_reports_status_created_idx
  on public.studio_user_reports(status, created_at desc);
create index if not exists studio_user_reports_studio_idx
  on public.studio_user_reports(studio_id, created_at desc);
alter table public.studio_user_reports enable row level security;
revoke all on public.studio_user_reports from anon;
grant insert, select on public.studio_user_reports to authenticated;
grant all on public.studio_user_reports to service_role;
drop policy if exists "users submit studio reports" on public.studio_user_reports;
create policy "users submit studio reports" on public.studio_user_reports
for insert to authenticated with check (reporter_id=auth.uid());
drop policy if exists "admins view studio reports" on public.studio_user_reports;
create policy "admins view studio reports" on public.studio_user_reports
for select to authenticated using (public.is_balletmate_admin());
drop policy if exists "admins update studio reports" on public.studio_user_reports;
create policy "admins update studio reports" on public.studio_user_reports
for update to authenticated using (public.is_balletmate_admin()) with check (public.is_balletmate_admin());
